/** Small DOM and event helpers shared by the UI modules. */

type Attrs = Record<string, string | number | boolean | null | undefined | EventListener>;
type Child = Node | string | null | undefined | false;

/**
 * Creates an element: `h('button.primary', { onclick }, 'Run')`. The tag may carry
 * `.class` and `#id` suffixes. Attributes starting with `on` become listeners.
 */
export function h<K extends keyof HTMLElementTagNameMap>(tag: K | `${K}${'.' | '#'}${string}`, attrs?: Attrs | null, ...children: Child[]): HTMLElementTagNameMap[K];
export function h(tag: string, attrs?: Attrs | null, ...children: Child[]): HTMLElement {
  const [, name, rest = ''] = /^([a-z0-9-]+)(.*)$/i.exec(tag) ?? [, 'div', ''];
  const el = document.createElement(name);
  for (const part of rest.match(/[.#][^.#]+/g) ?? []) {
    if (part[0] === '.') el.classList.add(part.slice(1));
    else el.id = part.slice(1);
  }
  for (const [key, value] of Object.entries(attrs ?? {})) {
    if (value === null || value === undefined || value === false) continue;
    if (key.startsWith('on') && typeof value === 'function') el.addEventListener(key.slice(2), value as EventListener);
    else if (key === 'class') el.classList.add(...String(value).split(/\s+/).filter(Boolean));
    else if (value === true) el.setAttribute(key, '');
    else el.setAttribute(key, String(value));
  }
  for (const child of children) if (child) el.append(child);
  return el;
}

